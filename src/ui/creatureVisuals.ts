/** A closed outline around a limb's centreline, tapering from `w0` wide at the body to `w1` at the
 *  foot, with a small splayed foot. */
function limb(path: [number, number][], w0: number, w1: number): [number, number][] {
  const left: [number, number][] = [], right: [number, number][] = [];
  path.forEach(([x, y], i) => {
    const [ax, ay] = path[Math.max(0, i - 1)], [bx, by] = path[Math.min(path.length - 1, i + 1)];
    const len = Math.hypot(bx - ax, by - ay) || 1;
    const nx = -(by - ay) / len, ny = (bx - ax) / len;
    const h = (w0 + (w1 - w0) * (i / (path.length - 1))) / 2;
    left.push([x + nx * h, y + ny * h]);
    right.push([x - nx * h, y - ny * h]);
  });
  const [fx, fy] = path[path.length - 1];
  return [...left, [fx - w1, fy - 2], [fx + w1, fy - 2], ...right.reverse()];
}
